export function makeT(lang) {
  const d = STR[lang] || STR.en;
  return (key, vars) => {
    let v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), d);
    if (v == null) v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), STR.en);
    if (typeof v !== 'string') return v == null ? key : v;
    return vars ? v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m)) : v;
  };
}
export function pickLang(search, saved, navLang) {
  const q = new URLSearchParams(search || '').get('lang');
  if (q && LANGS.includes(q)) return q;
  if (saved && LANGS.includes(saved)) return saved;
  return String(navLang || '').toLowerCase().startsWith('es') ? 'es' : 'en';
}
